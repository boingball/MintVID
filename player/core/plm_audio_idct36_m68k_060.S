/* 68060-safe MP2 IDCT36 kernel.
 *
 * The 040-class plm_audio_idct36_m68k.S kernel uses the extended
 * register-pair muls.l <ea>,Dh:Dl (32x32->64) form at each of its 33
 * mul_q15-shaped multiplies - hardware on 68020/030/040, but an
 * "unimplemented integer instruction" trap on the 68060 (see CLAUDE.md's
 * "MPEG-1/2 (libmpeg2) notes"), which only implements the 32x32->32 form in
 * silicon. Until now 68060 fell back to plm_audio_idct36 (portable C,
 * itself routing through the inline-asm plm_audio_smul64_060 widen when
 * MR_CPU_68060 is defined) - correct and trap-free, but an interim path,
 * not a hand-tuned kernel of its own.
 *
 * This file is that kernel. smul64_060_shared is the same mulu.w-based
 * four-partial-product widen as plm_audio_smul64_060 in pl_mpeg.h (16x16->32
 * partial products, hardware on every m68k tier including the 060, combined
 * with plain adds/addx/swaps - never an extended-result MULS.L/MULU.L,
 * never an extended divide, never a libgcc __muldi3/__divdi3/__udivdi3
 * call). idct36's butterfly network is 33 back-to-back mul_q15 calls with
 * no loop - unrolling the widen multiply completely inline at each site (as
 * synth_window below does, where it costs nothing) would blow this
 * function out to roughly 35 KB, several times the 68060's 8 KB icache;
 * kept instead as one local, non-exported subroutine every call site
 * reaches through a plain jsr/rts, matching the ~11 KB size of the existing
 * 040 kernel. The apply-bias/shift-and-combine glue around each call
 * (mul_q15's rounding) is untouched from the portable path's math - only
 * the multiply itself changed.
 *
 * Generated by compiling a standalone C transliteration of
 * plm_audio_idct36()/plm_audio_mul_q15() (renamed, otherwise identical -
 * see CLAUDE.md) at -mcpu=68060 -O2 with the widen multiply as inline asm,
 * then stripping only the compiler's own bookkeeping directives (#APP/
 * #NO_APP, .file, .type, .size, .ident, .note.GNU-stack) - verified to
 * leave the emitted machine code byte-for-byte unchanged. Verified
 * bit-exact against the portable C oracle by tests/mr_mp2_idct_060_asm_check.c,
 * cross-built for real m68k and run under qemu-m68k at -mcpu=68060. A CI
 * disassembly check (tests/check_m68060_asm.sh) fails the build if this
 * object ever contains an extended-result MULS.L/MULU.L, an extended
 * divide, or a reference to __muldi3/__divdi3/__udivdi3 - not just that the
 * C source looks safe, the actual emitted 68060 machine code. Bit-exactness
 * is proven on qemu; the actual speedup on real 68060 silicon still needs a
 * hardware pass to confirm (see CLAUDE.md).
 */
